# ─────────────────────────────────────────────────────────────────────────────
# MAIN RENDER FUNCTION
# ─────────────────────────────────────────────────────────────────────────────
def render_results(results: List[SchemeResult], lang: str = "English",
                   profile: Optional[CitizenProfile] = None):

    is_marathi = (lang == "मराठी")
    eligible   = [r for r in results if r.status == "eligible"]
    almost     = [r for r in results if r.status == "almost"]
    ineligible = [r for r in results if r.status == "ineligible"]

    # ── Divider ──────────────────────────────────────────────────────────
    st.markdown(
        "<hr style='border:none; border-top:2px solid #E5E7EB; margin: 24px 0;'>",
        unsafe_allow_html=True
    )

    # ── Step 3 heading ────────────────────────────────────────────────────
    st.markdown(
        "<div style='font-size:15px;font-weight:700;color:#1B3A6B;"
        "text-transform:uppercase;letter-spacing:0.6px;margin-bottom:16px;'>"
        "Step 3 \u2014 Eligibility Results</div>",
        unsafe_allow_html=True
    )
    m1, m2, m3, m4 = st.columns(4)
    with m1:
        st.metric("Schemes Evaluated" if not is_marathi else "एकूण योजना", str(len(results)))
    with m2:
        st.metric("Eligible" if not is_marathi else "पात्र योजना", len(eligible),
                  delta="Qualified" if eligible else None)
    with m3:
        st.metric("Almost Eligible" if not is_marathi else "जवळपास पात्र", len(almost),
                  delta="Near-Miss" if almost else None)
    with m4:
        st.metric("Ineligible" if not is_marathi else "अपात्र योजना", len(ineligible))

    # ── Download & Search ─────────────────────────────────────────────────
    st.markdown("<div style='margin-top:16px;'></div>", unsafe_allow_html=True)
    da, db = st.columns([2.5, 1.2])
    with da:
        search_q = st.text_input(
            "Filter by scheme name or department keyword",
            placeholder="e.g. kisan, bahin, awas, pension…",
            key="results_search"
        ).strip().lower()
    with db:
        st.markdown("<div style='margin-top:28px;'></div>", unsafe_allow_html=True)
        report_txt = _download_report(results, profile)
        st.download_button(
            label="Download Eligibility Report" if not is_marathi else "अहवाल डाउनलोड करा",
            data=report_txt,
            file_name="maharashtra_eligibility_report.txt",
            mime="text/plain",
            use_container_width=True
        )

    def ok(r): return not search_q or search_q in r.name.lower() or search_q in r.department.lower()

    f_elig = [r for r in eligible   if ok(r)]
    f_alm  = [r for r in almost     if ok(r)]
    f_inel = [r for r in ineligible if ok(r)]

    # ── Tabs ──────────────────────────────────────────────────────────────
    st.markdown("<div style='margin-top:16px;'></div>", unsafe_allow_html=True)
    tab1, tab2, tab3, tab4 = st.tabs([
        f"Eligible ({len(f_elig)})"      if not is_marathi else f"पात्र ({len(f_elig)})",
        f"Almost Eligible ({len(f_alm)})" if not is_marathi else f"जवळपास पात्र ({len(f_alm)})",
        f"Ineligible ({len(f_inel)})"    if not is_marathi else f"अपात्र ({len(f_inel)})",
        "All Schemes"                    if not is_marathi else "सर्व योजना",
    ])

    with tab1:
        if f_elig:
            for r in f_elig:
                _eligible_card(r, is_marathi)
        else:
            st.info("No eligible schemes for this profile.")

    with tab2:
        if f_alm:
            st.markdown(
                f"<div style='background:#FFFBEB; border:1px solid #FDE68A; border-radius:6px; "
                f"padding:10px 14px; font-size:13px; color:#92400E; margin-bottom:16px;'>"
                f"<strong>Action Required —</strong> "
                f"You are exactly 1 condition away from qualifying for these schemes. "
                f"Follow the official remediation steps below."
                f"</div>" if not is_marathi else
                f"<div style='background:#FFFBEB; border:1px solid #FDE68A; border-radius:6px; "
                f"padding:10px 14px; font-size:13px; color:#92400E; margin-bottom:16px;'>"
                f"<strong>कृती आवश्यक —</strong> "
                f"या योजनांसाठी फक्त एक अट अपूर्ण आहे. खालील सूचनांचे पालन करा."
                f"</div>",
                unsafe_allow_html=True
            )
            for r in f_alm:
                _almost_card(r, is_marathi)
        else:
            st.info("No near-miss schemes for this profile.")

    with tab3:
        if f_inel:
            st.caption("These schemes failed 2 or more legal eligibility criteria." if not is_marathi
                       else "या योजनांसाठी दोन किंवा अधिक अटी पूर्ण झालेल्या नाहीत.")
            for r in f_inel:
                _ineligible_card(r, is_marathi)
        else:
            st.info("No ineligible schemes.")

    with tab4:
        for r in results:
            if not ok(r):
                continue
            colour = {"eligible": "#15803D", "almost": "#B45309", "ineligible": "#991B1B"}[r.status]
            st.markdown(
                f"<div style='border:1px solid #E5E7EB; border-radius:6px; padding:12px 16px; "
                f"margin-bottom:8px; display:flex; justify-content:space-between; align-items:center;'>"
                f"<div>"
                f"<div style='font-size:14px; font-weight:700; color:#1B3A6B;'>{r.name}</div>"
                f"<div style='font-size:12px; color:#6B7280;'>{r.department}</div>"
                f"<div style='font-size:12px; color:#374151; margin-top:4px;'>{r.description}</div>"
                f"</div>"
                f"<div style='text-align:right; min-width:100px;'>"
                f"<span style='background:{colour}22; color:{colour}; border:1px solid {colour}44; "
                f"padding:3px 10px; border-radius:12px; font-size:11px; font-weight:700; "
                f"text-transform:uppercase; letter-spacing:0.5px;'>{r.status}</span>"
                f"</div></div>",
                unsafe_allow_html=True
            )
