def _tts(text: str, lang_code: str, btn_label: str):
    """In-browser Web Speech API button — no emojis in label."""
    safe = text.replace('"', '\\"').replace("\n", " ").replace("'", "\\'")
    components.html(f"""
    <button onclick="(function(){{
        window.speechSynthesis.cancel();
        var u=new SpeechSynthesisUtterance('{safe}');
        u.lang='{lang_code}'; u.rate=0.92;
        window.speechSynthesis.speak(u);
    }})()" style="
        background:#1B3A6B; color:#fff;
        border:none; padding:6px 14px;
        border-radius:5px; font-size:12px;
        font-weight:600; cursor:pointer;
        letter-spacing:0.3px;
        font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;">
        {btn_label}
    </button>""", height=40)


def _download_report(results: List[SchemeResult], profile: Optional[CitizenProfile]) -> str:
    lines = [
        "GOVERNMENT OF MAHARASHTRA",
        "CITIZEN SCHEME ELIGIBILITY VERIFICATION SLIP",
        "=" * 64,
    ]
    if profile:
        lines += [
            f"Applicant   : {profile.name}",
            f"Age/Gender  : {profile.age} years / {profile.gender.capitalize()}",
            f"Income      : Rs. {profile.annual_income:,.0f}",
            f"Caste       : {profile.caste_category.upper()}",
            f"Land        : {profile.land_holding_hectares} Ha",
            f"Occupation  : {profile.occupation.replace('_',' ').capitalize()}",
            "-" * 64,
        ]
    eligible  = [r for r in results if r.status == "eligible"]
    almost    = [r for r in results if r.status == "almost"]
    ineligible= [r for r in results if r.status == "ineligible"]

    lines.append(f"\nI. ELIGIBLE SCHEMES ({len(eligible)})\n")
    for i, r in enumerate(eligible, 1):
        lines += [f"  {i}. {r.name}", f"     Department : {r.department}",
                  f"     Benefit    : {r.description}", f"     Eligibility: {r.explanation}",
                  f"     Apply At   : {r.source_url}", ""]
    lines.append(f"\nII. NEAR-MISS — ACTION REQUIRED ({len(almost)})\n")
    for i, r in enumerate(almost, 1):
        lines += [f"  {i}. {r.name}",
                  f"     Unmet Condition  : {r.failed_rules[0] if r.failed_rules else 'N/A'}",
                  f"     Remediation Steps: {r.almost_advice}", f"     Official Portal  : {r.source_url}", ""]
    lines.append(f"\nIII. INELIGIBLE ({len(ineligible)})\n")
    for i, r in enumerate(ineligible, 1):
        lines.append(f"  {i}. {r.name} — {', '.join(r.failed_rules[:2])}")
    lines += ["", "=" * 64,
              "Generated by Maharashtra Scheme Navigator — Deterministic Gazette Rule Engine"]
    return "\n".join(lines)


